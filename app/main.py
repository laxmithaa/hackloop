def create_application(settings: Settings | None = None) -> FastAPI:
    """Build a FastAPI application instance.

    ``settings`` overrides the environment-derived configuration; tests use it
    to build isolated applications without touching the local ``.env`` file.
    """

    app_settings = settings or get_settings()
    configure_logging(app_settings.log_level, force=True)

    @asynccontextmanager
    async def lifespan(application: FastAPI) -> AsyncIterator[None]:
        logger.info(
            "starting %s v%s environment=%s",
            app_settings.app_name,
            app_settings.app_version,
            app_settings.environment,
        )
        yield
        logger.info("shutting down %s", app_settings.app_name)

    application = FastAPI(
        title=app_settings.app_name,
        version=app_settings.app_version,
        description=API_DESCRIPTION,
        docs_url="/docs",
        redoc_url="/redoc",
        openapi_url="/openapi.json",
        openapi_tags=OPENAPI_TAGS,
        lifespan=lifespan,
    )

    application.state.settings = app_settings
    application.state.session_store = SessionStore(app_settings.session_ttl_minutes)
    application.state.records = InMemoryBillRecordAccess()
    application.state.ocr_adapter = build_ocr_adapter(app_settings)
    # Phase 4: help-request tickets (in-memory support-workflow records).
    application.state.help_request_store = HelpRequestStore()

    # Access-code digests are derived once, from the environment / local
    # .env values, then the plain codes are dropped. Values are never logged.
    provisioned = collect_provisioned_codes(
        environ=os.environ,
        backend_dir=BACKEND_DIR,
        records=application.state.records,
        iterations=app_settings.access_code_pbkdf2_iterations,
    )
    application.state.verification_service = VerificationService.build(
        records=application.state.records,
        session_store=application.state.session_store,
        digests=provisioned,
        challenge_ttl_minutes=app_settings.verification_challenge_ttl_minutes,
        max_attempts=app_settings.verification_max_attempts,
    )
    logger.info("access-code digests provisioned for %d fictional bill(s)", len(provisioned))

    # Phase 8: local-GenAI explanation layer (Ollama on localhost only).
    explanation_client = OllamaChatClient(
        base_url=app_settings.ollama_base_url,
        model=app_settings.ollama_model,
        timeout_seconds=app_settings.ollama_timeout_seconds,
        max_output_chars=app_settings.ollama_max_output_chars,
    )
    application.state.explanation_service = ExplanationService(explanation_client)

    application.add_middleware(
        CORSMiddleware,
        allow_origins=app_settings.cors_origins_list,
        allow_credentials=app_settings.cors_allow_credentials,
        allow_methods=["*"],
        allow_headers=["*"],
        expose_headers=[app_settings.request_id_header],
    )
    application.add_middleware(SecurityHeadersMiddleware)
    # Added last so it runs outermost and stamps every response, including
    # CORS preflight replies.
    application.add_middleware(RequestIdMiddleware, header_name=app_settings.request_id_header)

    register_exception_handlers(application)

    application.include_router(health_router)
    application.include_router(api_v1_router, prefix=app_settings.api_v1_prefix)

    return application


app = create_application()
