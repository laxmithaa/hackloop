"""FastAPI application entry point for the Healthcare Bill Navigator API.

Run locally with::

    uvicorn app.main:app --reload

This module exposes exactly one application instance (``app``); tests build
isolated instances with :func:`create_application` and their own settings.
"""

from __future__ import annotations

import logging
import os
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from app.api.error_handlers import register_exception_handlers
from app.api.routes.health import router as health_router
from app.api.v1.router import api_v1_router
from app.core.config import BACKEND_DIR, Settings, get_settings
from app.core.logging import configure_logging
from app.core.middleware import RequestIdMiddleware, SecurityHeadersMiddleware
from app.services.access_codes import collect_provisioned_codes
from app.services.explanations import ExplanationService
from app.services.help_requests import HelpRequestStore
from app.services.ocr import build_ocr_adapter
from app.services.ollama_client import OllamaChatClient
from app.services.records import InMemoryBillRecordAccess
from app.services.session_store import SessionStore
from app.services.verification import VerificationService

logger = logging.getLogger(__name__)

API_DESCRIPTION = """
Backend for **Healthcare Bill Navigator**, a prototype that helps patients and
caregivers understand hospital bills and reach human support workers.

Phase 1 provides the platform foundation: environment-based configuration,
request correlation ids, consistent JSON errors, CORS and health reporting.
Phase 2 adds patient sessions and consent, temporary in-memory fictional
hospital/bill records, bill-image upload with local (non-generative) OCR via
Tesseract, and bill identification.

Phase 3 adds access-code verification (PBKDF2-hashed fictional demo codes,
three attempts, five-minute challenges) plus careful labelled amount
comparison between uploaded bills and the fictional records, and the
protected verified-bill endpoint that releases recorded amounts only after
successful verification.

All responses that are not `2xx` use one error envelope:
`{"error": {"code", "message", "request_id", "details"}}`.

Sessions, consent, identification and verification records live in process
memory and reset on restart. Identification and verification responses never
contain financial amounts; only `GET /api/v1/verified-bills/{id}` does, and
only after verification.

Phase 4 adds the human-support workflow: patients request a callback on one
of their identifications (with explicit, request-specific sharing consent)
and support workers manage a ticket status machine through token-secured
endpoints that fail closed. Callbacks are recorded as workflow status only —
no real call, SMS or email is ever placed by this prototype.

Phase 8 adds the first GenAI feature: a plain-language explanation of a
successfully verified bill, generated by a **locally running Ollama model**
(default ``qwen3:1.7b`` at ``http://localhost:11434``) — never a cloud AI
service. The model receives a minimal whitelisted summary, its prose is
validated against the authoritative record, and any model failure degrades
to deterministic backend text in the patient's language.
"""

